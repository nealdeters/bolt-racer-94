function ovalPoints(rx: number, rz: number, count: number): [number, number][] {
  const pts: [number, number][] = [];
  for (let i = 0; i < count; i++) {
    const a = (i / count) * Math.PI * 2;
    pts.push([Math.cos(a) * rx, Math.sin(a) * rz]);
  }
  return pts;
}

export function getTrack(id: string): TrackDef {
  const found = TRACKS.find((track) => track.id === id);
  if (!found) throw new Error(`Unknown track: ${id}`);
  return found;
}
